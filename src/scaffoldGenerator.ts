import { EvidenceGraph } from './graph';

export interface ComposeScaffoldResult {
  yaml: string;
  envExample: string;
}

export interface AdrResult {
  markdown: string;
  title: string;
}

function sanitizeServiceName(label: string): string {
  return label
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9_-]+/g, '-')
    .replace(/^-+|-+$/g, '') || 'service';
}

export function generateDockerComposeFromGraph(graph: EvidenceGraph): ComposeScaffoldResult {
  const services: Record<string, any> = {};
  const networks: Record<string, any> = {
    default: {
      name: 'archi-network',
    },
  };
  const envVars: Set<string> = new Set();

  for (const node of graph.nodes) {
    if (node.id.startsWith('group:')) continue;
    const name = sanitizeServiceName(node.label);

    if (node.kind === 'database') {
      const isMongo = /mongo/i.test(node.label);
      const isMysql = /mysql/i.test(node.label);
      services[name] = {
        image: isMongo ? 'mongo:7.0' : isMysql ? 'mysql:8.0' : 'postgres:16-alpine',
        restart: 'unless-stopped',
        environment: isMongo ? {
          MONGO_INITDB_ROOT_USERNAME: 'root',
          MONGO_INITDB_ROOT_PASSWORD: 'password',
        } : isMysql ? {
          MYSQL_ROOT_PASSWORD: 'password',
          MYSQL_DATABASE: 'app',
        } : {
          POSTGRES_USER: 'postgres',
          POSTGRES_PASSWORD: 'password',
          POSTGRES_DB: 'app',
        },
        ports: [isMongo ? '27017:27017' : isMysql ? '3306:3306' : '5432:5432'],
      };
      envVars.add(`${name.toUpperCase().replace(/-/g, '_')}_HOST=${name}`);
    } else if (node.kind === 'cache') {
      services[name] = {
        image: 'redis:7-alpine',
        restart: 'unless-stopped',
        ports: ['6379:6379'],
      };
      envVars.add(`${name.toUpperCase().replace(/-/g, '_')}_URL=redis://${name}:6379/0`);
    } else if (node.kind === 'broker') {
      const isRabbit = /rabbit/i.test(node.label);
      services[name] = isRabbit ? {
        image: 'rabbitmq:3-management-alpine',
        restart: 'unless-stopped',
        ports: ['5672:5672', '15672:15672'],
      } : {
        image: 'confluentinc/cp-kafka:7.5.0',
        restart: 'unless-stopped',
        ports: ['9092:9092'],
        environment: {
          KAFKA_NODE_ID: 1,
          KAFKA_LISTENER_SECURITY_PROTOCOL_MAP: 'CONTROLLER:PLAINTEXT,PLAINTEXT:PLAINTEXT',
          KAFKA_ADVERTISED_LISTENERS: 'PLAINTEXT://kafka:9092',
          KAFKA_PROCESS_ROLES: 'broker,controller',
          KAFKA_CONTROLLER_QUORUM_VOTERS: '1@kafka:9093',
          KAFKA_LISTENERS: 'PLAINTEXT://0.0.0.0:9092,CONTROLLER://0.0.0.0:9093',
          KAFKA_INTER_BROKER_LISTENER_NAME: 'PLAINTEXT',
          KAFKA_CONTROLLER_LISTENER_NAMES: 'CONTROLLER',
        },
      };
      envVars.add(`${name.toUpperCase().replace(/-/g, '_')}_HOST=${name}`);
    } else {
      // Application / Microservice / Gateway
      const outgoing = graph.edges.filter(e => e.from === node.id);
      const dependsOn = outgoing
        .map(e => graph.nodes.find(n => n.id === e.to))
        .filter((n): n is typeof graph.nodes[0] => !!n && !n.id.startsWith('group:'))
        .map(n => sanitizeServiceName(n.label));

      const isClient = /frontend|client|web|ui/i.test(node.label);
      const isGateway = /gateway|bff|proxy/i.test(node.label);
      const port = isClient ? 3000 : isGateway ? 8080 : 8000;

      services[name] = {
        build: {
          context: `./${name}`,
          dockerfile: 'Dockerfile',
        },
        restart: 'unless-stopped',
        ports: [`${port}:${port}`],
      };

      if (dependsOn.length > 0) {
        services[name].depends_on = [...new Set(dependsOn)];
      }
    }
  }

  // Format YAML manually or using JSON structure
  const yamlLines: string[] = ['# Generated by Archi 2.0 Scaffold Generator', 'version: "3.8"', '', 'services:'];

  for (const [svcName, svcConfig] of Object.entries(services)) {
    yamlLines.push(`  ${svcName}:`);
    if (svcConfig.image) {
      yamlLines.push(`    image: ${svcConfig.image}`);
    }
    if (svcConfig.build) {
      yamlLines.push('    build:');
      yamlLines.push(`      context: ${svcConfig.build.context}`);
      yamlLines.push(`      dockerfile: ${svcConfig.build.dockerfile}`);
    }
    yamlLines.push(`    restart: ${svcConfig.restart}`);
    if (svcConfig.ports && svcConfig.ports.length) {
      yamlLines.push('    ports:');
      for (const p of svcConfig.ports) {
        yamlLines.push(`      - "${p}"`);
      }
    }
    if (svcConfig.environment) {
      yamlLines.push('    environment:');
      for (const [k, v] of Object.entries(svcConfig.environment)) {
        yamlLines.push(`      ${k}: "${v}"`);
      }
    }
    if (svcConfig.depends_on && svcConfig.depends_on.length) {
      yamlLines.push('    depends_on:');
      for (const dep of svcConfig.depends_on) {
        yamlLines.push(`      - ${dep}`);
      }
    }
    yamlLines.push('');
  }

  yamlLines.push('networks:');
  yamlLines.push('  default:');
  yamlLines.push('    name: archi-network');

  const envLines: string[] = [
    '# Generated environment configuration template',
    ...[...envVars].sort(),
  ];

  return {
    yaml: yamlLines.join('\n') + '\n',
    envExample: envLines.join('\n') + '\n',
  };
}

export function generateAdrFromGraph(
  graph: EvidenceGraph,
  title: string = 'System Architecture Decision',
  status: string = 'Accepted'
): AdrResult {
  const date = new Date().toISOString().split('T')[0];
  const safeId = (id: string) => 'n' + id.replace(/[^a-zA-Z0-9]/g, '_');

  const mermaidLines = ['```mermaid', 'flowchart TD'];
  for (const node of graph.nodes) {
    if (node.id.startsWith('group:')) continue;
    mermaidLines.push(`  ${safeId(node.id)}["${node.label.replace(/"/g, "'")} (${node.kind})"]`);
  }
  for (const edge of graph.edges) {
    mermaidLines.push(`  ${safeId(edge.from)} -->|${edge.kind}${edge.label ? ': ' + edge.label : ''}| ${safeId(edge.to)}`);
  }
  mermaidLines.push('```');

  const markdown = `# ADR: ${title}

- **Date:** ${date}
- **Status:** ${status}
- **Author:** Archi Architecture Studio

## Context & Problem Statement
The system requires an intentional architectural topology that balances developer ergonomics, performance, and security boundaries.

## Proposed Architecture Topology
${mermaidLines.join('\n')}

## Component Catalog
${graph.nodes.filter(n => !n.id.startsWith('group:')).map(n => `- **${n.label}** (\`${n.kind}\`): ${n.group || 'Core'}`).join('\n')}

## Decision Consequences
- **Positive:** Clear separation of boundaries; dependencies declared statically.
- **Trade-offs:** Requires monitoring on cross-service latency and database connection pools.
`;

  return {
    title,
    markdown,
  };
}
